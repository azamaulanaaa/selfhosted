#!/usr/bin/env bash
# Generate the root compose.yaml from the service fragments in compose/.
# Write one include per fragment, in LC_ALL=C sort order.
# This script owns the root compose.yaml. Run setup.sh to regenerate the file.
set -euo pipefail

export LC_ALL=C

REPO_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"
readonly REPO_ROOT

readonly output='compose.yaml'
tmp_output="$(mktemp ./.compose.yaml.tmp.XXXXXX)"
trap 'rm -f -- "$tmp_output"' EXIT

# A null glob gives an empty list when no fragment exists. Sort the paths in C order.
shopt -s nullglob
fragments=(compose/*.yaml)
shopt -u nullglob
if ((${#fragments[@]} > 0)); then
  mapfile -t fragments < <(printf '%s\n' "${fragments[@]}" | sort)
fi

{
  printf 'name: services\n'
  printf '# Generated by setup.sh. Do not edit by hand. Run setup.sh to update.\n'
  if ((${#fragments[@]} > 0)); then
    printf 'include:\n'
    for fragment in "${fragments[@]}"; do
      printf '  - path: %s\n' "$fragment"
      printf '    project_directory: .\n'
      printf '    env_file: .env\n'
    done
  fi
  # Rootless nerdctl resolves a dotted vhost name through the host DNS. Pin the
  # shared network so the caddy vhosts use a static address that the app
  # containers can resolve with extra_hosts.
  printf 'networks:\n'
  printf '  default:\n'
  printf '    ipam:\n'
  printf '      config:\n'
  printf '        - subnet: 10.90.0.0/24\n'
} >"$tmp_output"

# Leave the file untouched when the content is identical. This makes the script idempotent.
if [ -f "$output" ] && cmp -s -- "$tmp_output" "$output"; then
  exit 0
fi
mv -- "$tmp_output" "$output"
