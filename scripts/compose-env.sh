#!/usr/bin/env bash
# Generate the Compose environment override for nerdctl.
# nerdctl compose ignores env_file, so this script reads every generated
# service environment file and writes the values into the override.
# Read config/<service>/<service>.env for each service that has one.
# Never read the root .env. Never print a value. Print the output path only.
set -euo pipefail

export LC_ALL=C

REPO_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"
readonly REPO_ROOT

readonly config_dir='config'
readonly output="$config_dir/compose.env.yaml"

mkdir -p "$config_dir"
tmp_output="$(mktemp "$config_dir/.compose.env.yaml.XXXXXX")"
trap 'rm -f -- "$tmp_output"' EXIT

# A null glob gives an empty list when no service directory exists.
shopt -s nullglob
service_dirs=("$config_dir"/*/)
shopt -u nullglob

{
  printf '# Generated by scripts/compose-env.sh. Do not edit.\n'
  wrote_service=0
  for service_dir in "${service_dirs[@]}"; do
    service="${service_dir%/}"
    service="${service##*/}"
    env_file="$config_dir/$service/$service.env"
    if [ ! -f "$env_file" ]; then
      continue
    fi
    wrote_entry=0
    while IFS= read -r line || [ -n "$line" ]; do
      if [[ "$line" =~ ^[[:space:]]*$ ]]; then
        continue
      fi
      line="${line#"${line%%[![:space:]]*}"}"
      if [ "${line:0:1}" = "#" ]; then
        continue
      fi
      escaped="${line//\'/\'\'}"
      if [ "$wrote_entry" -eq 0 ]; then
        if [ "$wrote_service" -eq 0 ]; then
          printf 'services:\n'
          wrote_service=1
        fi
        printf '  %s:\n' "$service"
        printf '    environment:\n'
        wrote_entry=1
      fi
      printf "      - '%s'\n" "$escaped"
    done <"$env_file"
  done
  if [ "$wrote_service" -eq 0 ]; then
    printf 'services: {}\n'
  fi
} >"$tmp_output"

chmod 0600 "$tmp_output"
mv -- "$tmp_output" "$output"
echo "Wrote the Compose environment override: $output"
